/** Writes `files` (path → content) under a new temporary folder and returns it. */
function writeTempFolder(files: Record<string, string>) {
  const root = mkdtempSync(join(tmpdir(), "menhir-styling-skill-"));
  for (const [path, content] of Object.entries(files)) {
    mkdirSync(join(root, path, ".."), { recursive: true });
    writeFileSync(join(root, path), content);
  }
  return root;
}

/** A look called "demo" with a Switch example, and a Dialog with none. */
const demo = {
  "looks/demo/LOOK.md": "# The demo look\n\nRound and grey.\n",
  "looks/demo/tokens.css": ":root {\n  --radius: 1rem;\n}\n",
  "looks/demo/LICENSE": "MIT License\n\nCopyright (c) Demo\n",
  "examples/switch/demo/SwitchExample.tsx": '<Switch.Root class="h-6" />\n',
  "examples/switch/demo/switch.css": ".switch {}\n",
  "examples/switch/tailwind/SwitchExample.tsx": "<Switch.Root />\n",
  "examples/dialog/tailwind/DialogExample.tsx": "<Dialog.Root />\n",
};

function generate(files: Record<string, string>) {
  const root = writeTempFolder(files);
  return stylingSkillLooks({
    root,
    looks: join(root, "looks"),
    examples: join(root, "examples"),
  });
}

describe("stylingSkillLooks", () => {
  test("turns a look's example into a Markdown file, TSX first, linked to the component's page", () => {
    expect(generate(demo).get("demo/switch.md")).toBe(
      `<!-- Generated by website/styling-skill.ts from examples/switch/demo/. Edit those files, then run \`pnpm --filter website skill\`. -->

# Switch in the demo look

Its parts, props and data attributes: [Switch](https://menhir-ui.com/docs/components/switch.md).

## SwitchExample.tsx

\`\`\`tsx
<Switch.Root class="h-6" />
\`\`\`

## switch.css

\`\`\`css
.switch {}
\`\`\`
`,
    );
  });

  test("copies the look's guide, tokens and licence, and makes nothing for a component without an example in it", () => {
    const files = generate(demo);
    expect([...files.keys()].sort()).toEqual([
      "demo/LICENSE",
      "demo/LOOK.md",
      "demo/switch.md",
      "demo/tokens.css",
    ]);
    expect(files.get("demo/LOOK.md")).toBe(
      `<!-- Generated by website/styling-skill.ts from looks/demo/LOOK.md. Edit that file, then run \`pnpm --filter website skill\`. -->

# The demo look

Round and grey.

## Worked examples

- [Switch](switch.md)
`,
    );
    expect(files.get("demo/tokens.css")).toBe(
      `/* Generated by website/styling-skill.ts from looks/demo/tokens.css. Edit that file, then run \`pnpm --filter website skill\`. */

:root {
  --radius: 1rem;
}
`,
    );
    expect(files.get("demo/LICENSE")).toBe(
      "MIT License\n\nCopyright (c) Demo\n",
    );
  });
});

describe("packages/menhir/skills/menhir-styling", () => {
  const generated = stylingSkillLooks(defaultSources);
  const lookNames = [...generated.keys()]
    .filter((path) => path.endsWith("/LOOK.md"))
    .map((path) => path.split("/")[0]!)
    .sort();
  /** The names of the components that have a worked example in `look`, sorted. */
  const workedExamples = (look: string) =>
    [...generated.keys()]
      .filter((path) => path.startsWith(`${look}/`) && path.endsWith(".md"))
      .map((path) => path.slice(look.length + 1, -".md".length))
      .filter((slug) => slug !== "LOOK")
      .map(componentName)
      .sort();

  test("has the looks the website makes, unchanged", () => {
    const committed = new Map(
      globSync("**/*", { cwd: skillLooks, withFileTypes: true })
        .filter((entry) => entry.isFile())
        .map((entry) => {
          const path = join(entry.parentPath, entry.name);
          return [relative(skillLooks, path), readFileSync(path, "utf8")];
        }),
    );
    // On a failure, run `pnpm --filter website skill` and commit the result.
    expect(Object.fromEntries(committed)).toEqual(
      Object.fromEntries(generated),
    );
  });

  test("names every look in SKILL.md, and no other", () => {
    const skill = readFileSync(join(skillLooks, "../SKILL.md"), "utf8");
    const named = [...skill.matchAll(/\(looks\/([a-z0-9-]+)\/LOOK\.md\)/g)]
      .map((match) => match[1])
      .sort();
    expect(lookNames).not.toEqual([]);
    expect(named).toEqual(lookNames);
  });

  test("lists each look's worked examples in SKILL.md's table", () => {
    const skill = readFileSync(join(skillLooks, "../SKILL.md"), "utf8");
    for (const look of lookNames) {
      const row = skill
        .split("\n")
        .find((line) => line.includes(`(looks/${look}/LOOK.md)`));
      const listed = row!.split("|").at(-2)!.trim().split(", ").sort();
      expect(listed).toEqual(workedExamples(look));
    }
  });

  test("has every look in the website's list of looks, with its tokens imported in App.css", () => {
    expect(looks.map((look) => look.name).sort()).toEqual(lookNames);
    const appCss = readFileSync(
      join(defaultSources.looks, "../App.css"),
      "utf8",
    );
    for (const look of lookNames) {
      expect(appCss).toContain(`@import "./looks/${look}/tokens.css";`);
    }
  });
});

/**
 * A colour written as a value in a Tailwind class instead of a token: white,
 * black, a palette colour such as `stone-300`, or an arbitrary one.
 */
const literalColour =
  /\b(?:bg|text|border|ring|outline|fill|stroke|from|via|to|shadow|divide|decoration|accent|caret)-(?:white|black|(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d+|\[(?:#|rgb|hsl|oklch)[^\]]*\])[^\s"'`]*/g;

/** The colours each look's LOOK.md names as not being tokens, by look. */
const allowedLiteralColours: Record<string, string[]> = {
  shadcn: ["bg-black/50"],
};

describe("worked examples", () => {
  const generated = stylingSkillLooks(defaultSources);
  const workedExamples = [...generated].filter(
    ([path]) => path.endsWith(".md") && !path.endsWith("/LOOK.md"),
  );

  test("take every colour from a token, but for the ones the look's LOOK.md names", () => {
    expect(workedExamples).not.toEqual([]);
    for (const [path, markdown] of workedExamples) {
      const look = path.split("/")[0]!;
      const allowed = allowedLiteralColours[look] ?? [];
      const literal = (markdown.match(literalColour) ?? []).filter(
        (colour) => !allowed.includes(colour),
      );
      expect(literal, path).toEqual([]);
    }
    for (const [look, colours] of Object.entries(allowedLiteralColours)) {
      for (const colour of colours) {
        expect(generated.get(`${look}/LOOK.md`)).toContain(colour);
      }
    }
  });

  test("the colour check finds a palette colour, white and an arbitrary colour", () => {
    expect(
      'class="bg-stone-300 text-white dark:border-[#fff] bg-primary text-foreground/60"'.match(
        literalColour,
      ),
    ).toEqual(["bg-stone-300", "text-white", "border-[#fff]"]);
  });
});

describe("componentName", () => {
  test("gives every component the name its page has", () => {
    for (const doc of componentDocs) {
      expect(componentName(doc.slug)).toBe(doc.name);
    }
  });
});
