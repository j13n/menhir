describe("packages/menhir/skills/menhir-styling", () => {
  const generated = stylingSkillLooks(defaultSources);
  const lookNames = [...generated.keys()]
    .filter((path) => path.endsWith("/LOOK.md"))
    .map((path) => path.split("/")[0]!)
    .sort();
  /** The names of the components that have a worked example in `look`, sorted. */
  const workedExamples = (look: string) =>
    [...generated.keys()]
      .filter((path) => path.startsWith(`${look}/`) && path.endsWith(".md"))
      .map((path) => path.slice(look.length + 1, -".md".length))
      .filter((slug) => slug !== "LOOK")
      .map(componentName)
      .sort();

  test("has the looks the website makes, unchanged", () => {
    const committed = new Map(
      globSync("**/*", { cwd: skillLooks, withFileTypes: true })
        .filter((entry) => entry.isFile())
        .map((entry) => {
          const path = join(entry.parentPath, entry.name);
          return [relative(skillLooks, path), readFileSync(path, "utf8")];
        }),
    );
    // On a failure, run `pnpm --filter website skill` and commit the result.
    expect(Object.fromEntries(committed)).toEqual(
      Object.fromEntries(generated),
    );
  });

  test("names every look in SKILL.md, and no other", () => {
    const skill = readFileSync(join(skillLooks, "../SKILL.md"), "utf8");
    const named = [...skill.matchAll(/\(looks\/([a-z0-9-]+)\/LOOK\.md\)/g)]
      .map((match) => match[1])
      .sort();
    expect(lookNames).not.toEqual([]);
    expect(named).toEqual(lookNames);
  });

  test("lists each look's worked examples in SKILL.md's table", () => {
    const skill = readFileSync(join(skillLooks, "../SKILL.md"), "utf8");
    for (const look of lookNames) {
      const row = skill
        .split("\n")
        .find((line) => line.includes(`(looks/${look}/LOOK.md)`));
      const listed = row!.split("|").at(-2)!.trim().split(", ").sort();
      expect(listed).toEqual(workedExamples(look));
    }
  });

  test("has every look in the website's list of looks, with its tokens imported in App.css", () => {
    expect(looks.map((look) => look.name).sort()).toEqual(lookNames);
    const appCss = readFileSync(
      join(defaultSources.looks, "../App.css"),
      "utf8",
    );
    for (const look of lookNames) {
      expect(appCss).toContain(`@import "./looks/${look}/tokens.css";`);
    }
  });
});

/**
 * A colour written as a value in a Tailwind class instead of a token: white,
 * black, a palette colour such as `stone-300`, or an arbitrary one.
 */
const literalColour =
  /\b(?:bg|text|border|ring|outline|fill|stroke|from|via|to|shadow|divide|decoration|accent|caret)-(?:white|black|(?:slate|gray|zinc|neutral|stone|red|orange|amber|yellow|lime|green|emerald|teal|cyan|sky|blue|indigo|violet|purple|fuchsia|pink|rose)-\d+|\[(?:#|rgb|hsl|oklch)[^\]]*\])[^\s"'`]*/g;

/** The colours each look's LOOK.md names as not being tokens, by look. */
const allowedLiteralColours: Record<string, string[]> = {
  shadcn: ["bg-black/50"],
};

describe("worked examples", () => {
  const generated = stylingSkillLooks(defaultSources);
  const workedExamples = [...generated].filter(
    ([path]) => path.endsWith(".md") && !path.endsWith("/LOOK.md"),
  );

  test("take every colour from a token, but for the ones the look's LOOK.md names", () => {
    expect(workedExamples).not.toEqual([]);
    for (const [path, markdown] of workedExamples) {
      const look = path.split("/")[0]!;
      const allowed = allowedLiteralColours[look] ?? [];
      const literal = (markdown.match(literalColour) ?? []).filter(
        (colour) => !allowed.includes(colour),
      );
      expect(literal, path).toEqual([]);
    }
    for (const [look, colours] of Object.entries(allowedLiteralColours)) {
      for (const colour of colours) {
        expect(generated.get(`${look}/LOOK.md`)).toContain(colour);
      }
    }
  });

  test("the colour check finds a palette colour, white and an arbitrary colour", () => {
    expect(
      'class="bg-stone-300 text-white dark:border-[#fff] bg-primary text-foreground/60"'.match(
        literalColour,
      ),
    ).toEqual(["bg-stone-300", "text-white", "border-[#fff]"]);
  });
});

/**
 * A colour written as a value in CSS instead of a token: a hex colour, a
 * colour function, or one of the basic named colours. `color-mix()` of two
 * tokens, `transparent` and `currentColor` are not.
 */
const literalCssColour =
  /#[0-9a-f]{3,8}\b|\b(?:rgba?|hsla?|hwb|lab|lch|oklab|oklch|color)\(|(?<![-\w])(?:black|silver|gr[ae]y|white|maroon|red|purple|fuchsia|green|lime|olive|yellow|navy|blue|teal|aqua|orange)(?![-\w(])/gi;

/** The literal colours in `css`, its comments aside. */
const literalCssColours = (css: string) =>
  css.replace(/\/\*[\s\S]*?\*\//g, "").match(literalCssColour) ?? [];

/** The content of every fenced `css` block in a Markdown file, joined. */
const cssBlocks = (markdown: string) =>
  [...markdown.matchAll(/```css\n([\s\S]*?)```/g)]
    .map((match) => match[1])
    .join("\n");

/** A look's stylesheets that set its tokens, and so hold its colours. */
const tokenFiles = ["tokens.css", "tokens.tailwind.css"];

describe.each(looks.filter((look) => look.styling === "css"))(
  "the $name look, in plain CSS",
  (look) => {
    const generated = stylingSkillLooks(defaultSources);
    const files = [...generated].filter(([path]) =>
      path.startsWith(`${look.name}/`),
    );
    const file = (name: string) => generated.get(`${look.name}/${name}`)!;

    test("takes every colour from a token: in its modules, its worked examples and its recipes", () => {
      const checked = files.filter(
        ([path]) => !tokenFiles.some((name) => path.endsWith(`/${name}`)),
      );
      expect(checked.map(([path]) => path)).toContain(`${look.name}/LOOK.md`);
      for (const [path, content] of checked) {
        if (path.endsWith("/LICENSE")) continue;
        const css = path.endsWith(".md") ? cssBlocks(content) : content;
        expect(literalCssColours(css), path).toEqual([]);
      }
    });

    test("has no global class: every stylesheet but its tokens is a CSS module", () => {
      const stylesheets = [
        ...globSync("*.css", { cwd: join(defaultSources.looks, look.name) }),
        ...globSync(`*/${look.name}/*.css`, { cwd: defaultSources.examples }),
      ].filter((path) => !tokenFiles.includes(path));
      expect(stylesheets).not.toEqual([]);
      expect(
        stylesheets.filter((path) => !path.endsWith(".module.css")),
      ).toEqual([]);
      // A class written as a string is a global one.
      for (const path of globSync(`*/${look.name}/*.tsx`, {
        cwd: defaultSources.examples,
      })) {
        const source = readFileSync(
          join(defaultSources.examples, path),
          "utf8",
        );
        expect(source, path).not.toMatch(/\bclass="/);
      }
    });

    test("gives every token a Tailwind name in tokens.tailwind.css, but for the ones LOOK.md names", () => {
      const tokens = [...file("tokens.css").matchAll(/^\s*(--[\w-]+):/gm)].map(
        (match) => match[1]!,
      );
      expect(tokens).not.toEqual([]);
      const theme = [
        ...file("tokens.tailwind.css").matchAll(/^\s*--[\w-]+:\s*(.+);$/gm),
      ].map((match) => match[1]!);
      // No value of its own: each name is a var() of one token.
      const named = theme.map(
        (value) => value.match(/^var\((--[\w-]+)\)$/)?.[1],
      );
      expect(named).not.toContain(undefined);
      expect(named.filter((token) => !tokens.includes(token!))).toEqual([]);
      const unnamed = tokens.filter((token) => !named.includes(token));
      expect(unnamed.sort()).toEqual(
        [...(withoutTailwindName[look.name] ?? [])].sort(),
      );
      for (const token of unnamed) {
        expect(file("LOOK.md")).toMatch(
          new RegExp(`\`${token}\` is \`[^\`]+\``),
        );
      }
    });
  },
);

/** The tokens Tailwind has no theme key for, which the look's LOOK.md gives a class for. */
const withoutTailwindName: Record<string, string[]> = {
  bootstrap: [
    "--bs-border-width",
    "--bs-focus-ring-width",
    "--bs-body-font-weight",
  ],
};

describe("the CSS colour check", () => {
  test("finds a hex colour, a colour function and a named colour", () => {
    expect(
      literalCssColours(
        ".a { color: #fff; background: rgb(0 0 0 / 0.5); border-color: white; outline-color: oklch(1 0 0); }",
      ),
    ).toEqual(["#fff", "rgb(", "white", "oklch("]);
  });

  test("leaves a token, a mix of two tokens, a comment and white-space alone", () => {
    expect(
      literalCssColours(
        "/* black */ .a { color: var(--bs-white); white-space: nowrap; background: color-mix(in srgb, var(--bs-black) 15%, transparent); border-color: currentColor; }",
      ),
    ).toEqual([]);
  });
});

