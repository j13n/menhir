// Builds the looks of Menhir's styling skill from the website, so that the
// skill's worked examples are the ones the component pages render. Run
// `pnpm --filter website skill` after changing a look or one of its examples;
// styling-skill.test.ts fails while the committed files differ.
import {
  mkdirSync,
  readdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, extname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

/** Where a look's sources and the examples live, and the root that paths in the headers are relative to. */
export type StylingSkillSources = {
  root: string;
  looks: string;
  examples: string;
};

/** The absolute path of a path relative to the website folder. */
const websitePath = (relativePath: string) =>
  fileURLToPath(new URL(relativePath, import.meta.url));

/** The website's looks and examples, with paths relative to the repository. */
export const defaultSources: StylingSkillSources = {
  root: websitePath(".."),
  looks: websitePath("src/looks"),
  examples: websitePath("src/examples"),
};

/** The skill's `looks/` folder in the package, which this file writes. */
export const skillLooks = websitePath(
  "../packages/menhir/skills/menhir-styling/looks",
);

/** Replaces the skill's `looks/` folder with what the website makes now. */
export function writeStylingSkillLooks() {
  rmSync(skillLooks, { recursive: true, force: true });
  for (const [file, content] of stylingSkillLooks(defaultSources)) {
    mkdirSync(dirname(join(skillLooks, file)), { recursive: true });
    writeFileSync(join(skillLooks, file), content);
  }
}

if (import.meta.main) writeStylingSkillLooks();

/**
 * The files of the styling skill's `looks/` folder, by path inside it, made
 * from the website: each look's own files in `src/looks/<look>/`, and each
 * component's example in that look, `src/examples/<slug>/<look>/`.
 */
export function stylingSkillLooks(
  sources: StylingSkillSources,
): Map<string, string> {
  const files = new Map<string, string>();
  for (const look of folderNames(sources.looks)) {
    const lookDir = join(sources.looks, look);
    const read = (file: string) => readFileSync(join(lookDir, file), "utf8");
    const source = (file: string) =>
      relative(sources.root, join(lookDir, file));

    const slugs = folderNames(sources.examples).filter((slug) =>
      folderNames(join(sources.examples, slug)).includes(look),
    );
    for (const slug of slugs) {
      files.set(`${look}/${slug}.md`, exampleMarkdown(sources, slug, look));
    }

    const examples = slugs
      .map((slug) => `- [${componentName(slug)}](${slug}.md)`)
      .join("\n");
    files.set(
      `${look}/LOOK.md`,
      `${generatedComment(source("LOOK.md"), "that file")}\n\n${read("LOOK.md").trimEnd()}\n\n## Worked examples\n\n${examples}\n`,
    );
    files.set(
      `${look}/tokens.css`,
      `/* ${generatedNote(source("tokens.css"), "that file")} */\n\n${read("tokens.css")}`,
    );
    files.set(`${look}/LICENSE`, read("LICENSE"));
  }
  return files;
}

/** One component's example in a look, as Markdown: its files, TSX first. */
function exampleMarkdown(
  sources: StylingSkillSources,
  slug: string,
  look: string,
) {
  const dir = join(sources.examples, slug, look);
  const name = componentName(slug);
  const isTsx = (file: string) => file.endsWith(".tsx");
  const blocks = [
    generatedComment(`${relative(sources.root, dir)}/`, "those files"),
    `# ${name} in the ${look} look`,
    `Its parts, props and data attributes: [${name}](https://menhir-ui.com/docs/components/${slug}.md).`,
    ...readdirSync(dir)
      .toSorted(
        (a, b) => Number(isTsx(b)) - Number(isTsx(a)) || a.localeCompare(b),
      )
      .flatMap((file) => [
        `## ${file}`,
        `\`\`\`${extname(file).slice(1)}\n${readFileSync(join(dir, file), "utf8").trimEnd()}\n\`\`\``,
      ]),
  ];
  return `${blocks.join("\n\n")}\n`;
}

function generatedNote(source: string, editTarget: string) {
  return `Generated by website/styling-skill.ts from ${source}. Edit ${editTarget}, then run \`pnpm --filter website skill\`.`;
}

function generatedComment(source: string, editTarget: string) {
  return `<!-- ${generatedNote(source, editTarget)} -->`;
}

/**
 * "toggle-group" → "Toggle Group". The names are in src/componentDocs/, which
 * plain Node cannot import; styling-skill.test.ts checks that this gives the
 * same name for every component.
 */
export function componentName(slug: string) {
  return slug
    .split("-")
    .map((word) => word[0]!.toUpperCase() + word.slice(1))
    .join(" ");
}

/** The names of the folders in `dir`, sorted. */
function folderNames(dir: string) {
  return readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => entry.name)
    .sort();
}
