import { createContext, useContext } from "solid-js";
import { isDev } from "@solidjs/web";

/**
 * The field's state as `data-*` attributes, each `""` when it applies and
 * absent otherwise. Every part merges the same object, so its getters are
 * read where each element uses them.
 */
export type FieldStateAttributes = {
  readonly "data-invalid": "" | undefined;
  readonly "data-touched": "" | undefined;
  readonly "data-disabled": "" | undefined;
};

/** An Error part, as it registers with the Root once mounted. */
export interface FieldErrorEntry {
  /** Its `id`, which the control names while it is rendered. */
  id(): string | false;
  /** Whether it is rendered. */
  shown(): boolean;
}

/** What the Root shares with its parts. */
export interface FieldRootContextValue {
  /** The control's `id`, generated by the Root. */
  readonly controlId: string;
  /** The Description's `id`, generated by the Root. */
  readonly descriptionId: string;
  /** The field's `name`, for the control. */
  name(): string | undefined;
  /** Whether the field is disabled, for the control. */
  disabled(): boolean | undefined;
  /** Whether the field shows an error: invalid, and touched. */
  showsError(): boolean;
  /** The message an Error without children shows. */
  message(): string | undefined;
  /** The browser's validity of the first invalid control, if any. */
  validity(): ValidityState | undefined;
  /** The `id`s the control names in `aria-describedby`, if any. */
  describedBy(): string | undefined;
  /**
   * Counts a mounted Description, so the control names it. Returns what
   * uncounts it, for the Description's disposal.
   */
  registerDescription(): () => void;
  /**
   * Registers a mounted Error. Returns what unregisters it, for the
   * Error's disposal.
   */
  registerError(entry: FieldErrorEntry): () => void;
  /** The `data-*` attributes every part carries. */
  readonly attributes: FieldStateAttributes;
}

// `null` outside a Root, so that the part can name what is missing. Solid's
// own error for a context with no provider and no default does not.
export const FieldRootContext = createContext<FieldRootContextValue | null>(
  null,
);

export function useFieldRootContext(): FieldRootContextValue {
  const context = useContext(FieldRootContext);
  // Production builds drop the check, and its message, with `isDev`.
  if (isDev && !context) {
    throw new Error("[menhir] Field parts must be placed within <Field.Root>.");
  }
  return context!;
}
